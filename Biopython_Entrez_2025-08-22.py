# Collect MeSH terms from publications
## Fetch PMIDs for each faculty member
Entrez.email = "sarkisj@uci.edu"
pmid_list = []

for index, row in faculty_df.iterrows():
    rate_limit_entrez()  # Add delay before each request
    search_term = row["Faculty_Author_Affiliation"]
    try:
        handle_search = Entrez.esearch(db="pubmed", mindate="2022", maxdate="2025", term=search_term)
        record = Entrez.read(handle_search)
        pmid_list.append(record["IdList"])
        handle_search.close()
        print(f"Fetched PMIDs for faculty {index + 1}/{len(faculty_df)}")  # Progress tracking
    except Exception as e:
        print(f"Error fetching PMIDs for {search_term}: {e}")
        pmid_list.append([])  # Add empty list if error occurs

faculty_df["pmids"] = pmid_list

## Fetch MeSH terms for each PMID
Entrez.email = "sarkisj@uci.edu"
all_pub_mesh_terms = []

for index, row in faculty_df.iterrows():
    pmid_list = row['pmids'] 
    mesh_term_texts = []
    
    if not pmid_list:  # Skip if no PMIDs
        all_pub_mesh_terms.append('')
        continue
    
    # Process PMIDs in batches of 100 instead of one by one
    batch_size = 100
    for i in range(0, len(pmid_list), batch_size):
        rate_limit_entrez()  # Add delay before each batch
        batch_pmids = pmid_list[i:i + batch_size]
        pmid_string = ','.join(batch_pmids)  # Combine PMIDs for batch request
        
        try:
            handle_mesh = Entrez.efetch(db="pubmed", id=pmid_string, rettype="xml")
            records = Entrez.read(handle_mesh)
            handle_mesh.close()
            
            # Process all records in the batch
            for record in records["PubmedArticle"]:
                medline = record["MedlineCitation"]
                mesh_headings = medline.get("MeshHeadingList", [])
                for mesh_heading in mesh_headings:
                    descriptor_name_element = mesh_heading.get("DescriptorName")
                    if descriptor_name_element:
                        descriptor_name = str(descriptor_name_element)
                        mesh_term_texts.append(descriptor_name)
        except Exception as e:
            print(f"Error fetching MeSH terms for batch: {e}")
            continue
    
    all_pub_mesh_terms.append('; '.join(mesh_term_texts))
    print(f"Processed MeSH terms for faculty {index + 1}/{len(faculty_df)}")  # Progress tracking

faculty_df['pub_mesh_terms'] = all_pub_mesh_terms

# Save checkpoint so you don't have to run API calls again
faculty_df.to_csv('pubmed_mesh_terms_checkpoint.csv', index=False)
print("Checkpoint saved: PubMed data fetched successfully!")

