# Calculate normalized scores
def calculate_weighted_normalized_scores(terms_with_weights, top_items_list):
    """Calculate normalized scores using proper weighting"""
    if not terms_with_weights:
        return {item: 0.0 for item in top_items_list}
    
    weighted_counts = {}
    total_weighted_count = 0
    
    for term, weight in terms_with_weights:
        if term in top_items_list:
            weighted_counts[term] = weighted_counts.get(term, 0) + weight
            total_weighted_count += weight
    
    if total_weighted_count == 0:
        return {item: 0.0 for item in top_items_list}
    
    normalized_scores = {}
    for item in top_items_list:
        normalized_scores[item] = weighted_counts.get(item, 0) / total_weighted_count
    
    return normalized_scores

# Get top items list
