def combine_mesh_terms_with_weights(row):
    """Combine terms while tracking their sources for weighting"""
    terms_with_weights = []
    
    # Publications (weight = 1)
    if row['pub_mesh_terms'] and row['pub_mesh_terms'].strip():
        pub_terms = [term.strip() for term in row['pub_mesh_terms'].split(';') if term.strip()]
        terms_with_weights.extend([(term, 1) for term in pub_terms])
    
    # Mapped terms (weight = 2)  
    if row['Mapped_Mesh_Terms'] and row['Mapped_Mesh_Terms'].strip():
        mapped_terms = [term.strip() for term in row['Mapped_Mesh_Terms'].split(';') if term.strip()]
        terms_with_weights.extend([(term, 2) for term in mapped_terms])
    
    # Proposal terms (weight = 3)
    if row['Proposal_Mesh_Terms'] and row['Proposal_Mesh_Terms'].strip():
        proposal_terms = [term.strip() for term in row['Proposal_Mesh_Terms'].split(';') if term.strip()]
        terms_with_weights.extend([(term, 3) for term in proposal_terms])
    
    return terms_with_weights

